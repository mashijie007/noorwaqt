/** 解包为格点数组：每个格点带有单位球面坐标，供投影时直接使用 */
function unpack() {
  const bin = atob(MASK_B64);
  const bit = (i) => (bin.charCodeAt(i >> 3) >> (7 - (i & 7))) & 1;
  const cells = [];
  let idx = 0;
  const D = Math.PI / 180;
  for (let lat = GRID.latMin; lat <= GRID.latMax + 1e-9; lat += GRID.latStep) {
    const n = Math.max(1, Math.round(GRID.lonDensity * Math.cos(lat * D)));
    for (let i = 0; i < n; i++) {
      const isLand = bit(idx++);
      if (!isLand) continue;
      const lon = -180 + (360 * i) / n;
      const phi = lat * D, lam = lon * D;
      const cp = Math.cos(phi);
      // 单位球面向量（Y 轴为地轴）
      cells.push(cp * Math.sin(lam), Math.sin(phi), cp * Math.cos(lam));
    }
  }
  return new Float32Array(cells);
}

/** 扁平化的 xyz 三元组，长度 = 陆地点数 × 3 */
export const LAND = unpack();
export const LAND_COUNT = LAND.length / 3;
